const normalize = question => question.toLocaleLowerCase('ru-RU').replace(/ё/g,'е').replace(/[\s?!.,]+$/,'').trimStart().replace(/\s+/g,' ');

export function mockAsk(question) {
  // shortcut: exact demo examples stand in for retrieval until BM25 and an approved corpus are available.
  const normalized = normalize(question);
  const match = examples.find(example => example.questions.some(item => normalize(item) === normalized));
  return match ? { answer:match.answer, sources:match.sources } : { answer:'В документах нет этой информации.', sources:[] };
}
